import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../../../..')
const require = createRequire(join(root, 'package.json'))
const compiler = require.resolve('typescript/package.json')
const native = createRequire(compiler).resolve(
  `@typescript/typescript-${process.platform}-${process.arch}/package.json`
)
const libraries = readdirSync(join(dirname(native), 'lib'))
  .filter((name) => /^lib.*\.d\.ts$/.test(name))
  .sort()
const file = join(root, 'src/shared/orcad-artifacts.ts')
const source = readFileSync(file, 'utf8')
const lines = []
for (let index = 0; index < libraries.length; index += 6) {
  lines.push(libraries.slice(index, index + 6).join(' '))
}
const generated = `// Generated by config/scripts/assets/typescript-libraries/generate-typescript-library-artifacts.mjs.
export const ORCAD_TYPESCRIPT_LIBRARY_ARTIFACTS = \`
${lines.join('\n')}
\`
  .trim()
  .split(/\\s+/)
  .map((name) => \`\${TYPESCRIPT_LANGUAGE_SERVER_DIRECTORY}/\${name}\`)
`
const start = source.indexOf('// Generated by config/scripts/assets/typescript-libraries/')
const end = source.indexOf('\nexport function typeScriptLanguageServerBinary', start)
if (start === -1 || end === -1) {
  throw new Error('TypeScript library manifest markers are missing')
}
const next = source.slice(0, start) + generated + source.slice(end)
if (process.argv.includes('--check')) {
  if (next !== source) {
    throw new Error('TypeScript library artifacts need regeneration')
  }
} else {
  writeFileSync(file, next)
}
